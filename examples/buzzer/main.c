#include <xc.h>

#define _XTAL_FREQ 4000000

/* 关闭看门狗，避免程序等待按键释放时发生非预期复位。 */
#pragma config WDTE = OFF

/*
 * 按键触发有源蜂鸣器示例
 *
 * 硬件连接：
 *   GP2 -> 有源蜂鸣器控制端，高电平发声
 *   GP3 -> 按键输入，按下时为低电平
 *
 * 有源蜂鸣器内部自带振荡电路，因此这里只需输出持续 50 ms 的高电平，无需
 * 像无源蜂鸣器那样由软件生成音频方波。每次完整按下只发出一次短鸣。
 */
void main(void)
{
    /* 仅 GP2 配置为输出；GP3 保持输入以读取按键。 */
    TRISGPIO = 0b111011;

    /* 初始化为低电平，确保蜂鸣器上电后保持静音。 */
    GPIO = 0;

    while (1) {
        /* 按键为低有效；第一次检测只作为可能按下的信号。 */
        if (GP3 == 0) {
            /* 延时后复查输入，过滤按下瞬间的机械抖动。 */
            __delay_ms(20);
            if (GP3 == 0) {
                /* 输出一个 50 ms 的高电平脉冲，让有源蜂鸣器短鸣一次。 */
                GP2 = 1;
                __delay_ms(50);
                GP2 = 0;

                /* 等待释放，避免长按期间重复发声。 */
                while (GP3 == 0) {
                    NOP();
                }

                /* 过滤释放瞬间的触点抖动。 */
                __delay_ms(20);
            }
        }
    }
}
