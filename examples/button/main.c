#include <xc.h>

#define _XTAL_FREQ 4000000

/* 关闭看门狗，避免等待按键期间发生非预期复位。 */
#pragma config WDTE = OFF

/*
 * 按键切换双色 LED 示例
 *
 * 硬件连接：
 *   GP0 -> 第一颗 LED
 *   GP1 -> 第二颗 LED
 *   GP3 -> 按键，按下时输入低电平
 *
 * 每次确认一次完整的“按下并释放”后，程序交换 GP0、GP1 的电平，因此两颗
 * LED 会交替点亮。按下和释放阶段各延时 20 ms，用于过滤机械触点抖动。
 */
void main(void)
{
    /* 初始仅点亮连接在 GP0 上的 LED。 */
    unsigned char led_state = 0b000001;

    /*
     * GP0、GP1 配置为输出；GP2 保持输入；GP3 在 PIC10F200 上只能作为输入，
     * 正好用于读取按键状态。
     */
    TRISGPIO = 0b111100;
    GPIO = led_state;

    while (1) {
        /* 第一次检测到低电平，只表示按键可能被按下。 */
        if (GP3 == 0) {
            /* 等待触点趋于稳定后再次采样，完成按下消抖。 */
            __delay_ms(20);
            if (GP3 == 0) {
                /*
                 * 同时翻转低两位：状态在 01 和 10 之间切换，不会出现两颗
                 * LED 同时点亮或同时熄灭。
                 */
                led_state ^= 0b000011;
                GPIO = led_state;

                /*
                 * 等待本次按键释放，防止主循环把一次长按识别为多次操作。
                 * 等待期间用 NOP 保持处理器运行，但不改变任何输出。
                 */
                while (GP3 == 0) {
                    NOP();
                }

                /* 释放后再消抖，避免释放瞬间的抖动触发下一次切换。 */
                __delay_ms(20);
            }
        }
    }
}
